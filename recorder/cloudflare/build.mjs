// Bundles Voice Booth into a single Worker script (dist/worker.js) served at /record.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '../web');
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8' };
const files = {};
for (const f of fs.readdirSync(web)) {
  const buf = fs.readFileSync(path.join(web, f));
  files[f] = { type: TYPES[path.extname(f)] || 'text/plain; charset=utf-8', body: buf.toString('utf8'),
    etag: '"' + crypto.createHash('sha1').update(buf).digest('hex').slice(0, 16) + '"' };
}
const worker = '// Generated by build.mjs: Voice Booth, served at /record.\n' +
  'const FILES = ' + JSON.stringify(files) + ';\n' + `
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (url.pathname === '/record') { url.pathname = '/record/'; return Response.redirect(url.toString(), 301); }
    let rel = url.pathname.replace(/^[/]record[/]?/, '');
    if (rel === '') rel = 'index.html';
    const f = FILES[rel];
    if (!f) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
    // the microphone is the only thing the page may use; nothing is sent anywhere
    const headers = { 'content-type': f.type, etag: f.etag, 'cache-control': 'no-cache',
      'permissions-policy': 'microphone=(self)', 'content-security-policy': "default-src 'self'; script-src 'self' blob:; style-src 'self' 'unsafe-inline'; worker-src blob:" };
    if (request.headers.get('if-none-match') === f.etag) return new Response(null, { status: 304, headers });
    return new Response(f.body, { headers });
  },
};
`;
fs.mkdirSync(path.join(here, 'dist'), { recursive: true });
fs.writeFileSync(path.join(here, 'dist/worker.js'), worker);
console.log('dist/worker.js', Math.round(worker.length / 1024), 'KB,', Object.keys(files).length, 'files');
