// Bundles the web app into a single Worker script (dist/worker.js) that
// serves it under /boba. Text files are stored as strings, the rest base64.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '../web');
execFileSync('node', [path.resolve(here, '../tools/make-web.mjs')], { stdio: 'inherit' });

const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml',
  '.txt': 'text/plain; charset=utf-8', '.png': 'image/png', '.woff2': 'font/woff2',
};
const files = {};
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const full = path.join(dir, f), rel = path.relative(web, full).split(path.sep).join('/');
    if (fs.statSync(full).isDirectory()) { walk(full); continue; }
    if (rel === 'blank.html' || rel.startsWith('media/')) continue;     // media goes up as assets
    const type = TYPES[path.extname(f)] || 'application/octet-stream';
    const buf = fs.readFileSync(full);
    const text = /^text\/|json|svg/.test(type);
    files[rel] = { type, text, body: text ? buf.toString('utf8') : buf.toString('base64'),
      etag: '"' + crypto.createHash('sha1').update(buf).digest('hex').slice(0, 16) + '"' };
  }
})(web);
// the Android app, offered as a download from the song menu; like the
// video it goes up as a static asset rather than inside the script
const apk = path.resolve(here, '../dist/BobaBeats.apk');

const worker = `// Generated by build.mjs: Boba Beats, served at /boba.
const FILES = ${JSON.stringify(files)};
const bytes = (b64) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));

// Video players (Safari above all) ask for a file in pieces with a Range
// header and refuse to play without a proper 206 answer.
async function media(request, env) {
  const res = await env.ASSETS.fetch(new Request(request.url));
  if (!res.ok) return res;
  const type = res.headers.get('content-type') || 'application/octet-stream';
  const range = request.headers.get('range');
  const apk = request.url.endsWith('.apk');
  const base = { 'content-type': apk ? 'application/vnd.android.package-archive' : type, 'accept-ranges': 'bytes',
    'cache-control': apk ? 'no-cache' : 'public, max-age=86400',
    ...(apk ? { 'content-disposition': 'attachment; filename="BobaBeats.apk"' } : {}) };
  if (!range) return new Response(res.body, { headers: { ...base, 'content-length': res.headers.get('content-length') || '' } });
  const buf = await res.arrayBuffer(), size = buf.byteLength;
  const m = /bytes=([0-9]*)-([0-9]*)/.exec(range);
  let a = m && m[1] !== '' ? +m[1] : NaN, b = m && m[2] !== '' ? +m[2] : NaN;
  if (Number.isNaN(a)) { a = size - (Number.isNaN(b) ? size : b); b = size - 1; }
  if (Number.isNaN(b) || b >= size) b = size - 1;
  if (!m || a > b || a >= size) return new Response(null, { status: 416, headers: { ...base, 'content-range': 'bytes */' + size } });
  return new Response(buf.slice(a, b + 1), { status: 206, headers: { ...base, 'content-range': 'bytes ' + a + '-' + b + '/' + size, 'content-length': String(b - a + 1) } });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.pathname.startsWith('/boba/media/') || url.pathname === '/boba/BobaBeats.apk') return media(request, env);
    // the page uses relative links, so /boba must become /boba/
    if (url.pathname === '/boba') { url.pathname = '/boba/'; return Response.redirect(url.toString(), 301); }
    let rel = decodeURIComponent(url.pathname.replace(/^\\/boba\\/?/, ''));
    if (rel === '' || rel.endsWith('/')) rel += 'index.html';
    const f = FILES[rel];
    if (!f) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
    const headers = { 'content-type': f.type, etag: f.etag, ...(f.download ? { 'content-disposition': 'attachment; filename="' + f.download + '"' } : {}),
      // the page and the service worker are always checked for a newer version;
      // everything else is named in the service worker's list and versioned with it
      'cache-control': /\\.(html|webmanifest)$|^sw\\.js$/.test(rel) ? 'no-cache' : 'public, max-age=3600' };
    if (request.headers.get('if-none-match') === f.etag) return new Response(null, { status: 304, headers });
    return new Response(f.text ? f.body : bytes(f.body), { headers });
  },
};
`;
fs.rmSync(path.join(here, 'dist'), { recursive: true, force: true });
fs.mkdirSync(path.join(here, 'dist'));
fs.mkdirSync(path.join(here, 'dist/assets/boba'), { recursive: true });
if (fs.existsSync(path.join(web, 'media'))) fs.cpSync(path.join(web, 'media'), path.join(here, 'dist/assets/boba/media'), { recursive: true });
if (fs.existsSync(apk)) fs.copyFileSync(apk, path.join(here, 'dist/assets/boba/BobaBeats.apk'));
fs.writeFileSync(path.join(here, 'dist/worker.js'), worker);
console.log(`bundled ${Object.keys(files).length} files, ${(worker.length / 1024).toFixed(0)} KB`);
