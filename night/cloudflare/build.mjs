// Bundles Deep Drift into a single Worker script (dist/worker.js) served at /night.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '../web');
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.txt': 'text/plain; charset=utf-8', '.woff2': 'font/woff2' };
const files = {};
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const full = path.join(dir, f), rel = path.relative(web, full).split(path.sep).join('/');
    if (fs.statSync(full).isDirectory()) { walk(full); continue; }
    const type = TYPES[path.extname(f)] || 'application/octet-stream', buf = fs.readFileSync(full), text = /^text\//.test(type);
    files[rel] = { type, text, body: text ? buf.toString('utf8') : buf.toString('base64'),
      etag: '"' + crypto.createHash('sha1').update(buf).digest('hex').slice(0, 16) + '"' };
  }
})(web);
const worker = '// Generated by build.mjs: Deep Drift, served at /night.\n' +
  'const FILES = ' + JSON.stringify(files) + ';\n' + `
const bytes = (b64) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (url.pathname === '/night') { url.pathname = '/night/'; return Response.redirect(url.toString(), 301); }
    let rel = decodeURIComponent(url.pathname.replace(/^[/]night[/]?/, ''));
    if (rel === '' || rel.endsWith('/')) rel += 'index.html';
    const f = FILES[rel];
    if (!f) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
    const headers = { 'content-type': f.type, etag: f.etag, 'cache-control': rel.endsWith('.html') || rel.endsWith('.js') ? 'no-cache' : 'public, max-age=86400' };
    if (request.headers.get('if-none-match') === f.etag) return new Response(null, { status: 304, headers });
    return new Response(f.text ? f.body : bytes(f.body), { headers });
  },
};
`;
fs.mkdirSync(path.join(here, 'dist'), { recursive: true });
fs.writeFileSync(path.join(here, 'dist/worker.js'), worker);
console.log('dist/worker.js', Math.round(worker.length / 1024), 'KB,', Object.keys(files).length, 'files');
