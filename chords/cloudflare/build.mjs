// Bundles Cozy Chords into a single Worker script (dist/worker.js) served at /chords.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '../web');
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.txt': 'text/plain; charset=utf-8', '.woff2': 'font/woff2', '.png': 'image/png', '.webmanifest': 'application/manifest+json; charset=utf-8' };
const files = {};
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const full = path.join(dir, f), rel = path.relative(web, full).split(path.sep).join('/');
    if (fs.statSync(full).isDirectory()) { walk(full); continue; }
    if (rel.startsWith('media/')) continue;                // big media goes up as static assets
    const type = TYPES[path.extname(f)] || 'application/octet-stream', buf = fs.readFileSync(full), text = /^text\//.test(type);
    files[rel] = { type, text, body: text ? buf.toString('utf8') : buf.toString('base64'),
      etag: '"' + crypto.createHash('sha1').update(buf).digest('hex').slice(0, 16) + '"' };
  }
})(web);
// The offline copy for the installed web app: a service worker that keeps
// every file above (not the big videos) and swaps to a new copy whenever
// any of them changes.
{
  const list = ['./', ...Object.keys(files).sort()];
  const version = crypto.createHash('sha1').update(list.map((k) => (files[k] ? files[k].etag : '')).join()).digest('hex').slice(0, 10);
  const body = `// Generated by build.mjs: keeps a copy of the app so it opens with no signal.
const CACHE = 'chords-${version}';
const FILES = ${JSON.stringify(list)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('chords-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`;
  files['sw.js'] = { type: TYPES['.js'], text: true, body, etag: '"' + crypto.createHash('sha1').update(body).digest('hex').slice(0, 16) + '"' };
}
const worker = '// Generated by build.mjs: Cozy Chords, served at /chords.\n' +
  'const FILES = ' + JSON.stringify(files) + ';\n' + `
const bytes = (b64) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));

// Video players (Safari above all) ask for a file in pieces with a Range
// header and refuse to play without a proper 206 answer.
async function media(request, env) {
  const res = await env.ASSETS.fetch(new Request(request.url));
  if (!res.ok) return res;
  const apk = request.url.endsWith('.apk');
  const base = { 'content-type': apk ? 'application/vnd.android.package-archive' : res.headers.get('content-type') || 'video/mp4', 'accept-ranges': 'bytes',
    'cache-control': apk ? 'no-cache' : 'public, max-age=86400', ...(apk ? { 'content-disposition': 'attachment; filename="CozyChords.apk"' } : {}) };
  const range = request.headers.get('range');
  if (!range) return new Response(res.body, { headers: { ...base, 'content-length': res.headers.get('content-length') || '' } });
  const buf = await res.arrayBuffer(), size = buf.byteLength;
  const m = /bytes=([0-9]*)-([0-9]*)/.exec(range);
  let a = m && m[1] !== '' ? +m[1] : NaN, b = m && m[2] !== '' ? +m[2] : NaN;
  if (Number.isNaN(a)) { a = size - (Number.isNaN(b) ? size : b); b = size - 1; }
  if (Number.isNaN(b) || b >= size) b = size - 1;
  if (!m || a > b || a >= size) return new Response(null, { status: 416, headers: { ...base, 'content-range': 'bytes */' + size } });
  return new Response(buf.slice(a, b + 1), { status: 206, headers: { ...base, 'content-range': 'bytes ' + a + '-' + b + '/' + size, 'content-length': String(b - a + 1) } });
}
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.pathname.startsWith('/chords/media/')) return media(request, env);
    if (url.pathname === '/chords') { url.pathname = '/chords/'; return Response.redirect(url.toString(), 301); }
    let rel = decodeURIComponent(url.pathname.replace(/^[/]chords[/]?/, ''));
    if (rel === '' || rel.endsWith('/')) rel += 'index.html';
    const f = FILES[rel];
    if (!f) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
    const headers = { 'content-type': f.type, etag: f.etag, ...(f.download ? { 'content-disposition': 'attachment; filename="' + f.download + '"' } : {}), 'cache-control': rel.endsWith('.html') || rel.endsWith('.js') || rel.endsWith('.css') ? 'no-cache' : 'public, max-age=86400' };
    if (request.headers.get('if-none-match') === f.etag) return new Response(null, { status: 304, headers });
    return new Response(f.text ? f.body : bytes(f.body), { headers });
  },
};
`;
fs.rmSync(path.join(here, 'dist'), { recursive: true, force: true });
fs.mkdirSync(path.join(here, 'dist/assets/chords'), { recursive: true });
if (fs.existsSync(path.join(web, 'media'))) fs.cpSync(path.join(web, 'media'), path.join(here, 'dist/assets/chords/media'), { recursive: true });
fs.writeFileSync(path.join(here, 'dist/worker.js'), worker);
console.log('dist/worker.js', Math.round(worker.length / 1024), 'KB,', Object.keys(files).length, 'files');
